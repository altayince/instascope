/**
 * One fixed Unicode lowercase rule for tokens and every stopword list. NFC keeps
 * accents composed; dotted capital İ lowers to i + dot, which we normalize to i.
 * Dotless ı, ß and other accents remain distinct. ASCII I follows Unicode's
 * default lowercase (i), not a guessed Turkish locale. This is not stemming or
 * full Unicode case folding: ß and ss are intentionally different tokens.
 */
export function normalizeWhatsAppWord(word: string): string {
  return word
    .normalize("NFC")
    .toLowerCase()
    .replace(/i\u0307/g, "i")
    .normalize("NFC");
}

