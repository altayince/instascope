/** All three languages apply together; no language detection or locale inference. */
const combinedStopwords: ReadonlySet<string> = new Set(
  [...TURKISH_STOPWORDS, ...GERMAN_STOPWORDS, ...ENGLISH_STOPWORDS].map(
    normalizeWhatsAppWord,
  ),
);

export function isWhatsAppStopword(word: string): boolean {
  return combinedStopwords.has(normalizeWhatsAppWord(word));
}
