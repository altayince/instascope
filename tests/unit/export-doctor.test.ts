import { describe, expect, it } from "vitest";
import { strToU8, zipSync } from "fflate";
import { exportDoctor } from "../../src/lib/analysis/export-doctor";
import { account } from "../../src/lib/instagram/normalize";
import { importDataset, importFiles } from "../../src/lib/instagram/import";
import { locateDirectory, ZIP_TAIL_BYTES } from "../../src/lib/instagram/zip";
import { connectionKinds } from "../../src/lib/instagram/connections";
import type { Dataset } from "../../src/lib/instagram/types";
import {
  createVaultSnapshot,
  serializeVaultBackup,
} from "../../src/lib/snapshot-vault";
import { createSavedSnapshot } from "../../src/lib/snapshot-storage";
import { buildStories } from "../../src/lib/analysis/stories";
import { analyze } from "../../src/lib/analysis/relationships";
import {
  htmlConnectionDocument,
  htmlLabelRecord,
  syntheticHtmlConnections,
  syntheticHtmlCore,
} from "../helpers/html-connection-export";

const input = (name: string, text: string) => ({ name, bytes: strToU8(text) });
const json = (name: string, value: unknown) =>
  input(name, JSON.stringify(value));
const rows = (values: { username: string; timestamp?: unknown }[]) =>
  values.map(({ username, timestamp }) => ({
    string_list_data: [{ value: username, timestamp }],
  }));
const core = [json("followers.json", []), json("following.json", [])];
const generatedHtml = (text: string, generation: string) =>
  text.replace(
    "<body>",
    `<body><header class="_as-_ _a70a"><div class="_a70d"><aside class="_aoaa" role="contentinfo">Generated by synthetic.owner on <time datetime="${generation}">Synthetic generation label</time></aside></div></header>`,
  );
const dataset = (
  followers: Dataset["followers"],
  following: Dataset["following"] = followers,
): Dataset => ({
  followers,
  following,
  metadata: { parsedAt: 9999999999999, sourceFormat: "legacy", warnings: [] },
});

describe("Export Doctor coverage and capabilities", () => {
  it("counts usable normalized dates with separate precision and factual coverage", () => {
    const data = dataset(
      [
        account("exact.one", 1704067200)!,
        account("exact.two", 1704153600)!,
        account("html.one", 1704240000, "minute-without-timezone")!,
        account("unknown")!,
      ],
      [account("following.unknown")!],
    );
    const report = exportDoctor(data);
    expect(report.core.followers).toMatchObject({
      records: 4,
      datedRecords: 3,
      dateCoverage: 75,
      exactDates: 2,
      timezoneUnknownDates: 1,
    });
    expect(report.core.following).toMatchObject({
      records: 1,
      datedRecords: 0,
      dateCoverage: 0,
    });
    expect(report.capabilities.relationshipDates).toBe(true);
    expect(report.capabilities.wrappedFollowingDates).toBe(false);
    expect(
      report.warnings.some((warning) => warning.code === "html-date-precision"),
    ).toBe(true);
  });

  it("has no percentage for an empty denominator and keeps valid empty core analysis ready", () => {
    const report = exportDoctor(importDataset(core));
    expect(report.core.followers).toMatchObject({
      records: 0,
      datedRecords: 0,
      exactDates: 0,
      timezoneUnknownDates: 0,
    });
    expect(report.core.followers.dateCoverage).toBeUndefined();
    expect(report.capabilities.coreRelationships).toBe(true);
    expect(report.capabilities.relationshipDates).toBe(false);
    expect(report.capabilities.wrappedDateStories).toBe(false);
  });

  it("excludes malformed timestamps and deduplicates normalized records", () => {
    const data = dataset([
      account("duplicate", 1704067200)!,
      account("DUPLICATE", 1704153600)!,
      { username: "malformed", href: "unused", timestamp: Number.NaN },
      account("missing")!,
    ]);
    const report = exportDoctor(data);
    expect(report.core.followers).toMatchObject({
      records: 3,
      datedRecords: 1,
    });
    expect(report.core.followers.dateCoverage).toBeCloseTo(100 / 3);
  });

  it("requires both recorded dates for a mutual and the actual Wrapped origin minimum", () => {
    const following = Array.from({ length: 10 }, (_, i) =>
      account(`mutual.${i}`, 1704153600)!,
    );
    const followers = following.map((entry) =>
      account(entry.username, 1704067200)!,
    );
    const full = exportDoctor(dataset(followers, following));
    expect(full.capabilities).toMatchObject({
      datedMutuals: 10,
      mutualOrigins: true,
      wrappedMutualOrigins: true,
      wrappedOriginMinimum: 10,
    });
    const limited = exportDoctor(dataset(followers.slice(0, 9), following));
    expect(limited.capabilities).toMatchObject({
      datedMutuals: 9,
      mutualOrigins: true,
      wrappedMutualOrigins: false,
      wrappedFollowingDates: true,
    });
    const noDates = exportDoctor(
      dataset(
        followers,
        following.map((entry) => account(entry.username)!),
      ),
    );
    expect(noDates.capabilities).toMatchObject({
      datedMutuals: 0,
      mutualOrigins: false,
      wrappedDateStories: false,
    });
    const stories = buildStories(
      analyze(dataset(followers, following)),
      dataset(followers, following),
      null,
    );
    expect(stories.some((story) => story.id === "origins")).toBe(
      full.capabilities.wrappedMutualOrigins,
    );
  });

  it("distinguishes available-empty, missing and unsupported optional categories", () => {
    const data = importDataset([
      ...core,
      json("pending_follow_requests.json", []),
      json("close_friends.json", []),
      input("restricted_profiles.json", "{"),
    ]);
    const report = exportDoctor(data);
    expect(report.optional.closeFriends).toMatchObject({
      status: "available",
      records: 0,
      sourceFiles: 1,
    });
    expect(report.optional.blocked).toMatchObject({
      status: "missing",
      sourceFiles: 0,
    });
    expect(report.optional.blocked.records).toBeUndefined();
    expect(report.optional.restricted).toMatchObject({
      status: "unsupported",
      sourceFiles: 1,
    });
    expect(report.optional.restricted.records).toBeUndefined();
    expect(report.capabilities).toMatchObject({
      pendingRequests: true,
      connectionPrivacy: "partial",
      availablePrivacyLists: 1,
      unfollowHistory: false,
    });
    expect(
      report.warnings.filter(
        (warning) => warning.code === "optional-unsupported",
      ),
    ).toHaveLength(1);
  });

  it("derives full, partial and unavailable privacy only from the four privacy list statuses", () => {
    const files = [
      "close_friends",
      "blocked_profiles",
      "restricted_profiles",
      "hide_story_from",
    ].map((name) => json(`${name}.json`, []));
    const full = exportDoctor(importDataset([...core, ...files]));
    expect(full.capabilities).toMatchObject({
      connectionPrivacy: "full",
      availablePrivacyLists: 4,
    });
    const none = exportDoctor(
      importDataset([
        ...core,
        json("pending_follow_requests.json", []),
        json("recently_unfollowed_profiles.json", []),
      ]),
    );
    expect(none.capabilities).toMatchObject({
      connectionPrivacy: "unavailable",
      availablePrivacyLists: 0,
      pendingRequests: true,
      unfollowHistory: true,
    });
  });

  it("does not infer source-file counts, content format, range or generation from legacy datasets", () => {
    const report = exportDoctor(dataset([account("very.old", 946684800)!]));
    expect(report.provenanceAvailable).toBe(false);
    expect(report.contentFormat).toBe("unknown");
    expect(report.sourceTransports).toBeUndefined();
    expect(report.core.followers.sourceFiles).toBeUndefined();
    expect(report.optional.closeFriends.sourceFiles).toBeUndefined();
    expect(report.archive.recognizedFiles).toBeUndefined();
    expect(report.archive.splitFollowers).toBeUndefined();
    expect(report.requestedRange).toBe("unknown");
    expect(report.generationDate).toBeUndefined();
  });

  it("does not infer All time or generation date from old dates, volume, filename or upload time", () => {
    const data = importDataset([
      json(
        "owner-private-path/followers_999.json",
        rows([{ username: "private.identity", timestamp: 946684800 }]),
      ),
      json("following.json", []),
    ]);
    data.metadata.parsedAt = Date.parse("2099-01-01T00:00:00Z");
    const report = exportDoctor(data);
    expect(report.requestedRange).toBe("unknown");
    expect(report.generationDate).toBeUndefined();
    expect(
      report.warnings.find(
        (warning) => warning.code === "requested-range-unknown",
      )?.message,
    ).toContain("cannot be verified");
    expect(JSON.stringify(report)).not.toMatch(
      /private\.identity|owner-private-path|followers_999|2099|946684800/,
    );
  });
});

describe("Aggregate import provenance", () => {
  it("counts combined core files once each and deduplicates split records", () => {
    const data = importDataset([
      json(
        "followers_1.json",
        rows([{ username: "same.identity", timestamp: 1704067200 }]),
      ),
      json(
        "followers_2.json",
        rows([
          { username: "same.identity", timestamp: 1704153600 },
          { username: "other.identity" },
        ]),
      ),
      json(
        "following_1.json",
        rows([{ username: "same.identity", timestamp: 1704153600 }]),
      ),
      json("following_2.json", []),
    ]);
    const report = exportDoctor(data);
    expect(report.archive).toMatchObject({
      recognizedFiles: 4,
      ignoredFiles: 0,
      splitFollowers: true,
      splitFollowing: true,
    });
    expect(report.core.followers).toMatchObject({
      sourceFiles: 2,
      jsonFiles: 2,
      records: 2,
      datedRecords: 1,
      dateCoverage: 50,
    });
    expect(report.core.following).toMatchObject({
      sourceFiles: 2,
      records: 1,
      datedRecords: 1,
    });
    expect(data.metadata.importProvenance!.categories.followers).toEqual({
      sourceFiles: 2,
      jsonFiles: 2,
      htmlFiles: 0,
      parsedFiles: 2,
      unsupportedFiles: 0,
      skippedFiles: 0,
    });
  });

  it("counts a generic JSON container with both core categories as one recognized file", () => {
    const data = importDataset([
      json("unclassified.json", {
        relationships_followers: [],
        relationships_following: [],
      }),
    ]);
    const report = exportDoctor(data);
    expect(report.archive.recognizedFiles).toBe(1);
    expect(report.core.followers.sourceFiles).toBe(1);
    expect(report.core.following.sourceFiles).toBe(1);
    expect(data.metadata.importProvenance!.contentFormats).toEqual({
      json: 1,
      html: 0,
    });
  });

  it("records parsed, unsupported and skipped optional files without changing all-or-nothing semantics", () => {
    const data = importDataset([
      ...core,
      json("blocked_profiles_1.json", []),
      input("blocked_profiles_2.html", "<main>broken</main>"),
      json("blocked_profiles_3.json", []),
    ]);
    expect(data.metadata.importProvenance!.categories.blocked).toEqual({
      sourceFiles: 3,
      jsonFiles: 2,
      htmlFiles: 1,
      parsedFiles: 1,
      unsupportedFiles: 1,
      skippedFiles: 1,
    });
    expect(exportDoctor(data).optional.blocked.records).toBeUndefined();
    expect(exportDoctor(data).archive).toMatchObject({
      recognizedFiles: 5,
      optionalSourceFiles: 3,
      optionalCategoriesFound: 1,
    });
    expect(data.connections!.blocked.accounts).toEqual([]);
  });

  it("keeps JSON timestamp priority in mixed HTML/JSON files and distinguishes content from transport", () => {
    const html = htmlConnectionDocument([
      `<div class="_a6-g"><a href="https://www.instagram.com/mixed.identity/">mixed.identity</a><p>Jan 01, 2024 12:00 am</p></div>`,
    ]);
    const data = importDataset([
      input("followers_1.html", html),
      json(
        "followers_2.json",
        rows([{ username: "mixed.identity", timestamp: 1704153600 }]),
      ),
      json("following.json", []),
    ]);
    expect(data.followers).toEqual([account("mixed.identity", 1704153600)]);
    const report = exportDoctor(data);
    expect(report.sourceFormat).toBe("html");
    expect(report.contentFormat).toBe("mixed");
    expect(report.sourceTransports).toEqual({ json: 2, html: 1, zip: 0 });
    expect(report.core.followers).toMatchObject({
      sourceFiles: 2,
      jsonFiles: 1,
      htmlFiles: 1,
      datedRecords: 1,
      exactDates: 1,
      timezoneUnknownDates: 0,
    });
  });

  it("collects ZIP ignored regular-file counts in the existing directory pass, excluding directories", async () => {
    const zip = zipSync({
      "connections/": strToU8(""),
      "unix-directory": strToU8(""),
      "dos-directory": strToU8(""),
      "connections/followers.json": strToU8("[]"),
      "connections/following.json": strToU8("[]"),
      "media/photo.jpg": strToU8("not read"),
      "recent_follow_requests.json": strToU8("not supported"),
    });
    const directory = locateDirectory(
      zip.subarray(Math.max(0, zip.length - ZIP_TAIL_BYTES)),
      zip.length,
    );
    const view = new DataView(zip.buffer);
    let cursor = directory.offset;
    for (let i = 0; i < directory.count; i++) {
      const length = view.getUint16(cursor + 28, true);
      const name = new TextDecoder().decode(
        zip.subarray(cursor + 46, cursor + 46 + length),
      );
      if (name === "unix-directory")
        view.setUint32(cursor + 38, 0x41ed0000, true);
      if (name === "dos-directory") view.setUint32(cursor + 38, 0x10, true);
      cursor +=
        46 +
        length +
        view.getUint16(cursor + 30, true) +
        view.getUint16(cursor + 32, true);
    }
    const sync = importDataset([
      { name: "private-archive-name.zip", bytes: zip },
    ]);
    const async = await importFiles([
      new File([zip], "private-archive-name.zip"),
    ]);
    expect(sync.metadata.importProvenance).toEqual(
      async.metadata.importProvenance,
    );
    expect(exportDoctor(sync).archive).toMatchObject({
      recognizedFiles: 2,
      ignoredFiles: 2,
    });
    expect(exportDoctor(sync).sourceTransports).toEqual({
      json: 0,
      html: 0,
      zip: 1,
    });
    expect(JSON.stringify(sync.metadata.importProvenance)).not.toMatch(
      /private-archive-name|photo\.jpg|connections\/|recent_follow_requests/,
    );
  });

  it("aggregates across multiple ZIPs and loose files without collapsing mixed sources", () => {
    const first = zipSync({
      "followers_1.json": strToU8("[]"),
      "following.json": strToU8("[]"),
      "ignored.txt": strToU8("ignored"),
    });
    const second = zipSync({
      "followers_2.html": strToU8("<h1>Followers</h1><p>No followers</p>"),
      "close_friends.html": strToU8(
        htmlConnectionDocument([
          htmlLabelRecord([["Username", "close.friend"]]),
        ]),
      ),
    });
    const report = exportDoctor(
      importDataset([
        { name: "first.zip", bytes: first },
        { name: "second.zip", bytes: second },
        json("blocked_profiles.json", []),
      ]),
    );
    expect(report.sourceFormat).toBe("zip");
    expect(report.sourceTransports).toEqual({ json: 1, html: 0, zip: 2 });
    expect(report.contentFormat).toBe("mixed");
    expect(report.archive).toMatchObject({
      recognizedFiles: 5,
      ignoredFiles: 1,
      splitFollowers: true,
      optionalCategoriesFound: 2,
      optionalSourceFiles: 2,
    });
  });

  it("reports verified INS-104 HTML structure without weakening category or timestamp semantics", () => {
    const files = { ...syntheticHtmlCore, ...syntheticHtmlConnections };
    const data = importDataset(
      Object.entries(files).map(([name, text]) => input(name, text)),
    );
    const report = exportDoctor(data);
    expect(report.contentFormat).toBe("html");
    expect(report.archive).toMatchObject({
      recognizedFiles: 9,
      splitFollowers: true,
      optionalCategoriesFound: 6,
      optionalSourceFiles: 6,
    });
    expect(report.core.followers).toMatchObject({
      records: 2,
      datedRecords: 1,
      dateCoverage: 50,
      exactDates: 0,
      timezoneUnknownDates: 1,
    });
    expect(report.core.following).toMatchObject({
      records: 1,
      datedRecords: 1,
      dateCoverage: 100,
      timezoneUnknownDates: 1,
    });
    expect(
      connectionKinds.every(
        (kind) => report.optional[kind].status === "available",
      ),
    ).toBe(true);
    expect(report.capabilities.connectionPrivacy).toBe("full");
  });

  it("keeps Doctor and provenance out of saved snapshot and Vault backup formats", () => {
    const data = importDataset([
      json(
        "followers_1.json",
        rows([{ username: "vault.identity", timestamp: 1704067200 }]),
      ),
      json("following.json", []),
    ]);
    const saved = createSavedSnapshot(data, "2025-01-01");
    const vault = createVaultSnapshot(data, "2025-01-01", "synthetic-vault", 1);
    expect(Object.keys(saved).sort()).toEqual([
      "exportDate",
      "followers",
      "following",
      "version",
    ]);
    expect(Object.keys(vault).sort()).toEqual([
      "createdAt",
      "exportDate",
      "followers",
      "following",
      "id",
      "version",
    ]);
    expect(serializeVaultBackup([vault])).not.toMatch(
      /importProvenance|Doctor|recognizedFiles|dateCoverage|sourceFormat|generationDate/,
    );
  });

  it("preserves existing hard failure for unreadable core relationship files", () => {
    expect(() =>
      importDataset([input("followers.json", "{"), json("following.json", [])]),
    ).toThrow(/damaged or incomplete/);
    expect(() => importDataset([json("followers.json", [])])).toThrow(
      /Missing Following/,
    );
  });
});

describe("Recorded HTML generation provenance", () => {
  const generation = "2025-01-05T13:05Z";
  const htmlFiles = (first = generation, second = generation) => [
    input(
      "followers.html",
      generatedHtml(syntheticHtmlCore["followers_1.html"], first),
    ),
    input(
      "following.html",
      generatedHtml(syntheticHtmlCore["following.html"], second),
    ),
  ];

  it("reports consistent generation minutes only from parsed relationship HTML, excluding other ZIP documents", () => {
    const files = htmlFiles();
    const zip = zipSync({
      ...Object.fromEntries(files.map((file) => [file.name, file.bytes])),
      "ignored/document.html": strToU8(
        generatedHtml(htmlConnectionDocument([]), "2025-01-05T13:06Z"),
      ),
    });
    const report = exportDoctor(
      importDataset([{ name: "synthetic.zip", bytes: zip }]),
    );
    expect(report).toMatchObject({
      generationDate: generation,
      generationDatedFiles: 2,
      generationCheckedFiles: 2,
      generationStatus: "consistent",
    });
    expect(report.generationDate).not.toContain(":05:00");
    expect(
      report.warnings.find(
        (warning) => warning.code === "generation-source-scope",
      )?.message,
    ).toContain("not a verified generation date for the whole ZIP");
    expect(report.requestedRange).toBe("unknown");
  });

  it("does not choose earliest, latest or a later matching observation when generation minutes conflict", () => {
    const files = htmlFiles(generation, "2025-01-05T13:06Z");
    files.push(
      input(
        "followers_2.html",
        generatedHtml(syntheticHtmlCore["followers_2.html"], generation),
      ),
    );
    for (const selected of [files, [...files].reverse()]) {
      const report = exportDoctor(importDataset(selected));
      expect(report.generationStatus).toBe("conflicting");
      expect(report.generationDatedFiles).toBe(3);
      expect(report.generationCheckedFiles).toBe(3);
      expect(report.generationDate).toBeUndefined();
      expect(
        report.warnings.find(
          (warning) => warning.code === "generation-date-unknown",
        )?.message,
      ).toContain("different generation times");
    }
  });

  it("retains scope counts when only some HTML files contain verified generation and JSON has none", () => {
    const report = exportDoctor(
      importDataset([
        htmlFiles()[0],
        input("following.html", syntheticHtmlCore["following.html"]),
        json("followers_2.json", []),
      ]),
    );
    expect(report).toMatchObject({
      generationDate: generation,
      generationStatus: "consistent",
      generationDatedFiles: 1,
      generationCheckedFiles: 2,
      contentFormat: "mixed",
    });
    expect(
      report.warnings.find(
        (warning) => warning.code === "generation-source-scope",
      )?.message,
    ).toContain("1 successfully parsed HTML");
  });

  it("does not derive generation from unsupported or skipped optional HTML files", () => {
    const report = exportDoctor(
      importDataset([
        ...htmlFiles(),
        input(
          "blocked_profiles_1.html",
          generatedHtml(
            htmlConnectionDocument([
              htmlLabelRecord([["Name", "not.identity"]]),
            ]),
            "2025-01-05T13:06Z",
          ),
        ),
        input(
          "blocked_profiles_2.html",
          generatedHtml(
            htmlConnectionDocument([
              htmlLabelRecord([["Username", "would.be.skipped"]]),
            ]),
            "2025-01-05T13:07Z",
          ),
        ),
      ]),
    );
    expect(report).toMatchObject({
      generationDate: generation,
      generationStatus: "consistent",
      generationDatedFiles: 2,
      generationCheckedFiles: 2,
    });
    expect(report.optional.blocked.status).toBe("unsupported");
    expect(report.optional.blocked.sourceFiles).toBe(2);
  });

  it("keeps unverified headers and timezone-free relationship dates separate", () => {
    const report = exportDoctor(
      importDataset(htmlFiles("2025-02-30T13:05Z", "2025-01-05T13:05")),
    );
    expect(report.generationStatus).toBe("unverified");
    expect(report.generationDate).toBeUndefined();
    expect(report.generationDatedFiles).toBe(0);
    expect(report.generationCheckedFiles).toBe(2);
    expect(report.core.followers.datedRecords).toBe(1);
    expect(report.core.followers.timezoneUnknownDates).toBe(1);
  });
});
