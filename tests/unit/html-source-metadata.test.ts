import { expect, it } from "vitest";
import { parseHtml, parseHtmlSource } from "../../src/lib/instagram/parsers";

const relationship =
  '<main><section><a href="https://www.instagram.com/synthetic.metadata/">synthetic.metadata</a><p>Jan 02, 2025 1:05 pm</p></section></main>';
const generation = (
  value: string,
  label = "Generated by Fictional owner on ",
) =>
  `<header class="_as-_ _a70a"><div class="_a70d"><aside class="_aoaa" role="contentinfo">${label}<time datetime="${value}">Synthetic displayed generation time</time></aside></div></header>`;

it("reads only the verified generation header's timezone-qualified minute without altering records", () => {
  const text = generation("2025-01-15T12:34Z") + relationship;
  const source = parseHtmlSource(text, "followers");
  expect(source.generationDate).toBe("2025-01-15T12:34Z");
  expect(source.parts).toEqual(parseHtml(text, "followers"));
  expect(source.parts[0].accounts[0].timestampPrecision).toBe(
    "minute-without-timezone",
  );
  expect(JSON.stringify(source)).not.toContain("Fictional owner");
});

it.each([
  "2025-02-30T12:34Z",
  "2025-13-01T12:34Z",
  "2025-01-15T24:34Z",
  "2025-01-15T12:60Z",
  "2025-01-15T12:34",
  "Jan 15, 2025 12:34 pm",
  "2025-01-15T12:34Z<script>",
])(
  "leaves malformed generation value %s unverified without failing usable core records",
  (value) => {
    const source = parseHtmlSource(
      generation(value) + relationship,
      "followers",
    );
    expect(source.generationDate).toBeUndefined();
    expect(source.parts[0].accounts).toHaveLength(1);
  },
);

it("does not infer generation from unrelated time elements, localised text or main dates", () => {
  for (const header of [
    '<header><time datetime="2025-01-15T12:34Z">A date</time></header>',
    generation("2025-01-15T12:34Z", "Unrelated date "),
    generation("2025-01-15T12:34Z", "Erstellt von Fictional owner am "),
    generation("2025-01-15T12:34Z").replace(
      'class="_as-_ _a70a"',
      'class="unrelated"',
    ),
  ])
    expect(
      parseHtmlSource(header + relationship, "followers").generationDate,
    ).toBeUndefined();
  const mainTime = relationship.replace(
    "</main>",
    '<time datetime="2025-01-15T12:34Z">Generated by Fictional owner on</time></main>',
  );
  expect(parseHtmlSource(mainTime, "followers").generationDate).toBeUndefined();
});

it("does not pick one conflicting or ambiguous header generation time", () => {
  expect(
    parseHtmlSource(
      generation("2025-01-15T12:34Z") +
        generation("2025-01-15T12:35Z") +
        relationship,
      "followers",
    ).generationDate,
  ).toBeUndefined();
  const two = generation("2025-01-15T12:34Z").replace(
    "</aside>",
    '<time datetime="2025-01-15T12:34Z">Another time</time></aside>',
  );
  expect(
    parseHtmlSource(two + relationship, "followers").generationDate,
  ).toBeUndefined();
});
